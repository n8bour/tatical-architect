pub fn t_name(tactic: &Tactic, lang: Lang) -> String {
    if tactic.name == "Nova tática" || tactic.name == "New tactic" {
        l(lang, "Nova tática", "New tactic").to_string()
    } else {
        tactic.name.clone()
    }
}
